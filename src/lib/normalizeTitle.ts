/**
 * 标题归一化：把同一部影片的不同命名（括号后缀、版本词、日文副标题、空白差异等）
 * 归一成统一的分组键，供聚合搜索合并重复结果使用。
 */
export function normalizeTitle(raw: string): string {
  if (!raw) return '';
  let t = raw.trim();

  // 1. 去除括号及其内容（中文/英文/方括号）
  t = t.replace(/[（【[(][^）】)\]]*[）】)\]]/g, '');

  // 2. 循环去除结尾的版本/语言/清晰度/解说等后缀，直到稳定
  const suffixPattern =
    /(普通话版|普通话|国语版|国语|粤语版|粤语|日语版|日语|英语版|英语|韩语版|韩语|法语版|法语|德语版|德语|泰语版|泰语|台配版|台配|中英双语|中英|中文字幕|中字|高清|超清|HD|完整版|未删减|导演剪辑版|加长版|修复版|重制版|抢先版|抢先|蓝光|BD|4K|1080P|720P|480P|电影解说|影视解说|剧情解说|解说|原声|无字|预告片|花絮|特辑|合集)$/gi;
  let prev: string;
  do {
    prev = t;
    t = t.replace(suffixPattern, '');
  } while (t !== prev);

  // 3. 日文副标题：标题含日文假名且有空格时，取空格前的主标题
  if (/[ぁ-んァ-ンー]/.test(t) && t.includes(' ')) {
    t = t.split(' ')[0];
  }

  // 4. 去所有空白（含全角空格）并转小写，作为稳定的分组键
  return t.replace(/\s+/g, '').toLowerCase();
}
